def setup_type(name):
    fields = {'supported': (bool, ...), 'reason': (str, ...),
              'object_name': (str, Field(min_length=1, max_length=80)),
              'surface_name': (str, Field(min_length=1, max_length=80))}
    if name in ('sliding', 'rolling'):
        fields['motion_mode'] = (Literal['coasting', 'constant_speed'], Field(
            description='coasting for passive slowing; constant_speed for externally maintained steady motion'))
    for key in REGISTRY[name].parameters:
        kind, bounds, description = FIELDS[key]
        fields[key] = (kind | None, Field(description=description + '; null unless explicitly stated', **bounds))
    return create_model(name + '_setup', __base__=dc.Output, **fields)


