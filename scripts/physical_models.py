class UnsupportedModel(ValueError):
    pass


MAX_RENDER_EVENTS = 8
# An unstated bounce count is derived: contacts continue while impulse relative to the first
# contact is at least this ratio (at gamma=1 the amplitude is also 10%, barely perceptible).
BOUNCE_STOP_RATIO = .10


def bounce_contacts(h, e, start=0., limit=64):
    """Contacts of a drop from rest above the stop ratio.

    Returns (physical_count, contact_times). physical_count is None when the bounce never
    decays (e = 1); times are listed up to `limit` contacts.
    """
    if e <= 0:
        physical = 1
    elif e >= 1:
        physical = None
    else:
        physical = math.floor(math.log(BOUNCE_STOP_RATIO) / math.log(e) + 1e-9) + 1
    v = math.sqrt(2 * G * h)
    t, times = start + math.sqrt(2 * h / G), []
    for _ in range(min(physical or limit, limit)):
        times.append(t)
        t += 2 * e * v / G
        v *= e
    return physical, times


def solve(name, setup, incoming=None, estimates=None):
    """Return physical process time separately from the vibration support window.

    Precedence per parameter: stated in text > inherited state > LM estimate > labeled default.
    """
    if not setup.supported:
        raise UnsupportedModel(setup.reason)
    raw = setup.model_dump()
    incoming = incoming or {}
    estimated = {k: v for k, v in (estimates.model_dump() if estimates else {}).items() if v['value'] is not None}
    values, origin, notes, omitted = {}, {}, [], {}

    def get(key, default=None, inherited=None):
        if raw.get(key) is not None:
            val, basis = raw[key], 'text_extracted_by_lm'
        elif inherited and incoming.get(inherited) is not None:
            val, basis = incoming[inherited], 'inherited_state'
        elif key in estimated:
            val, basis = estimated[key]['value'], 'estimated_by_lm'
        else:
            val, basis = default, 'assumed_default'
        values[key], origin[key] = val, basis
        return val

    start = get('start_s', 0.)
    obj, surface = raw['object_name'], raw['surface_name']
    source = f'{obj} / {surface}'
    captions = {'sliding': f'{obj} sliding against {surface}',
                'rolling': f'{obj} rolling over {surface}',
                'damped_oscillation': f'{obj} ringing with a fading vibration',
                'periodic': f'{obj} vibrating steadily',
                'stochastic': f'A single brief contact of {obj} against {surface}',
                'rhythmic_action': f'A single sharp impact of {obj} against {surface}'}
    prompt = captions.get(name, f'{obj} contacting {surface}')
    segments, samples, state = [], [], {}
    process_end = start
    equations = []

    def seg(at, duration, intensity=1., envelope=None, synthesis=None, caption=None):
        if duration <= 0 or intensity <= 0:
            return
        item = dict(source=source, prompt=caption or prompt, start=at,
                    duration=max(.15, duration), intensity=intensity)
        if duration < .15:
            notes.append('Physical duration <0.15s; rendering support extended to 0.15s without moving the physical boundary.')
        if envelope:
            item['envelope'] = envelope
        if synthesis:
            item['synthesis'] = synthesis
        segments.append(item)

    if name == 'vertical_bounce':
        h, e, mass = get('height_m', 1., 'height_m'), get('restitution', .7), get('mass_kg', .05, 'mass_kg')
        if incoming.get('vertical_velocity_m_s') not in (None, 0):
            raise UnsupportedModel('Drop-from-rest bounce model cannot inherit nonzero vertical velocity; use flight and impact models.')
        bounce_equations = []
        if raw.get('count') is not None:
            count = get('count')
        else:
            # Unstated count: the bounce continues while relative impulse e^(k-1) >= BOUNCE_STOP_RATIO.
            # Contacts past the render limit or the 10 s window are not output, only reported.
            physical, times = bounce_contacts(h, e, start)
            count = sum(1 for t in times[:MAX_RENDER_EVENTS] if t + .15 <= 10)
            values['count'], origin['count'] = count, 'derived_until_threshold'
            values['physical_contact_count'] = physical  # None = never decays (e = 1)
            origin['physical_contact_count'] = 'derived_until_threshold'
            bounce_equations = [f'count = number of contacts with e^(k-1) >= {BOUNCE_STOP_RATIO}']
            if physical is None or physical > count:
                reasons = (['restitution 1 never decays below the threshold'] if physical is None else []) + \
                          ([f'render limit of {MAX_RENDER_EVENTS} events'] if len(times) > MAX_RENDER_EVENTS else []) + \
                          (['10-second window'] if any(t + .15 > 10 for t in times[:MAX_RENDER_EVENTS]) else [])
                omitted.update(count=None if physical is None else physical - count, reason=', '.join(reasons),
                               first_omitted_time_s=times[count] if count < len(times) else None)
        b = bp.BounceSetup(supported=True, reason=raw['reason'], ball_material='unspecified',
                          surface_material='unspecified', drop_height_m=h, restitution=e,
                          mass_kg=mass, release_time_s=start, impact_count=count)
        r = bp.simulate(b)
        segments = [{**s, 'source': source, 'prompt': f'{obj} striking {surface} with a single impact'} for s in r['sub_events']]
        last = r['physics']['impacts'][-1]
        process_end = last['time_s']
        v = e * last['incoming_speed_m_s']
        state = dict(mass_kg=mass, height_m=0., vertical_velocity_m_s=v,
                     normal_speed_m_s=0., rebound_speed_m_s=v, energy_J=.5 * mass * v * v)
        samples = r['physics']['impacts']
        notes += r['physics']['notes']
        if origin['count'] == 'derived_until_threshold':
            notes.append(f'Contact count derived from restitution: contacts below {BOUNCE_STOP_RATIO:.0%} of the first impulse are treated as stopped.')
        else:
            notes.append('The excerpt ends just after its last collision; this is not physical rest or a bounce-to-roll conversion.')
        if omitted:
            notes.append(f"Omitted contacts not rendered ({omitted['reason']}): "
                         f"{'unbounded' if omitted['count'] is None else omitted['count']}.")
        equations = ['t1=start+sqrt(2h/g)', 'v_k=sqrt(2gh)*e^(k-1)', 'dt_k=2e*v_k/g'] + bounce_equations
    elif name == 'free_fall':
        h = get('height_m', 1., 'height_m')
        vy = get('vertical_velocity_m_s', 0., 'vertical_velocity_m_s')
        mass = get('mass_kg', .05, 'mass_kg')
        flight = (vy + math.sqrt(vy * vy + 2 * G * h)) / G
        velocity = vy - G * flight
        process_end = start + flight
        state = dict(mass_kg=mass, height_m=0., vertical_velocity_m_s=velocity,
                     normal_speed_m_s=-velocity, energy_J=.5 * mass * velocity * velocity)
        equations = ['h+vy*t-0.5*g*t^2=0', 'vy_out=vy-g*t']
        notes.append('Flight is silent; contact vibration belongs to a following impact model. Air drag is neglected.')
    elif name == 'single_impact':
        mass, speed, e = get('mass_kg', .05, 'mass_kg'), get('normal_speed_m_s', 1., 'normal_speed_m_s'), get('restitution', .2)
        impulse = mass * (1 + e) * speed
        rebound = e * speed
        if impulse > 0:
            seg(start, .15, caption=f'{obj} striking {surface} with a single impact')
        process_end = start  # instantaneous contact; render tail does not delay the next physical action
        state = dict(mass_kg=mass, height_m=0., rebound_speed_m_s=rebound,
                     impulse_N_s=impulse, energy_J=.5 * mass * rebound * rebound,
                     dissipated_energy_J=.5 * mass * speed * speed * (1-e*e))
        if incoming.get('vertical_velocity_m_s') is not None:
            state['vertical_velocity_m_s'] = rebound
        if incoming.get('horizontal_speed_m_s') is not None:
            state['horizontal_speed_m_s'] = rebound
            state['horizontal_direction_reversed'] = True
        samples = [dict(time_s=start, incoming_speed_m_s=speed, impulse_N_s=impulse)]
        equations = ['J=m*(1+e)*v_normal', 'v_out=e*v_normal']
        notes.append('Rigid fixed surface, normal impact; 0.15s is a rendering window, not contact duration.')
    elif name in ('sliding', 'rolling'):
        speed = get('speed_m_s', .8, 'horizontal_speed_m_s')
        mass = get('mass_kg', .05, 'mass_kg')
        key = 'friction_coefficient' if name == 'sliding' else 'rolling_resistance'
        coefficient = get(key, .3 if name == 'sliding' else .03)
        mode = raw['motion_mode']
        values['motion_mode'], origin['motion_mode'] = mode, 'interpreted_by_lm'
        acceleration = coefficient * G
        stop_time = speed / acceleration
        duration = get('duration_s', 2. if mode == 'constant_speed' else stop_time)
        if raw.get('duration_s') is None:
            origin['duration_s'] = 'assumed_default' if mode == 'constant_speed' else 'derived_stop_time'
        moving = duration if mode == 'constant_speed' else min(duration, stop_time)
        end_speed = speed if mode == 'constant_speed' else max(0., speed - acceleration * duration)
        distance = speed * duration if mode == 'constant_speed' else speed * moving - .5 * acceleration * moving * moving
        if speed:
            ratio = 1. if mode == 'constant_speed' else max(0., speed - acceleration * moving) / speed
            seg(start, moving, envelope={'kind': 'linear', 'end_ratio': ratio})
        process_end = start + duration
        state = dict(mass_kg=mass, horizontal_speed_m_s=end_speed, distance_m=distance,
                     energy_J=.5 * mass * end_speed * end_speed)
        samples = [dict(time_s=start, speed_m_s=speed), dict(time_s=process_end, speed_m_s=end_speed, distance_m=distance)]
        equations = ['a=coefficient*g', 'v=max(0,v0-a*t)', 'x=v0*t-0.5*a*t^2 while moving']
        notes.append('Envelope is a normalized speed proxy, not calibrated tactile force.')
        if mode == 'constant_speed':
            equations = ['F_external=F_resistance=coefficient*m*g', 'v=constant', 'x=v*T', 'P=F_resistance*v']
            values['required_drive_force_N'] = coefficient * mass * G
            origin['required_drive_force_N'] = 'derived_force_balance'
            notes.append('Maintained speed assumes an external drive exactly balances resistance; this force is not independently inferred or measured.')
        else:
            notes.append('Unpowered horizontal coasting with constant resistance, not maintained constant-speed motion.')
        if name == 'rolling':
            notes.append('Effective rolling resistance, not kinetic sliding friction. Radius/spin dynamics and bounce-to-roll conversion are not solved.')
    elif name in ('periodic', 'damped_oscillation'):
        frequency = get('frequency_hz', 120.)
        phase = incoming.get('phase_rad', 0.)
        if name == 'periodic':
            rpm = get('rpm', None)
            if rpm is not None and raw.get('frequency_hz') is None:
                frequency = rpm / 60.
                values['frequency_hz'], origin['frequency_hz'] = frequency, 'derived_from_rpm'
            elif rpm is not None and not math.isclose(frequency, rpm / 60., rel_tol=.01):
                raise ValueError('frequency_hz and rpm specify inconsistent single-cycle frequencies')
            duration = get('duration_s', 2.)
            env = None
            equations = ['x(t)=sin(2*pi*f*t+phase)', 'f=rpm/60 when one vibration cycle per revolution is assumed']
            notes.append('Single-frequency sinusoid; RPM mapping assumes one vibration cycle per revolution, not a measured motor spectrum.')
        else:
            zeta = get('damping_ratio', .03)
            excitation = get('excitation_energy_J', None, 'vibration_energy_J')
            tau = 1 / (zeta * 2 * math.pi * frequency)
            duration = get('duration_s', math.log(100) * tau)
            if raw.get('duration_s') is None:
                origin['duration_s'] = 'derived_1_percent_amplitude_threshold'
            frequency *= math.sqrt(1 - zeta * zeta)
            env = {'kind': 'exponential', 'tau_s': tau}
            equations = ['envelope=exp(-zeta*omega_n*t)', 'f_d=f_n*sqrt(1-zeta^2)']
            notes.append('Underdamped linear oscillator. Default endpoint is the design threshold of 1% amplitude, not exact physical rest.')
        if not 0 < frequency <= 500:
            raise ValueError('Analytic carrier must be in (0,500] Hz')
        seg(start, duration, envelope=env, synthesis={'kind': 'sine', 'frequency_hz': frequency, 'phase_rad': phase})
        process_end = start + duration
        state = {'phase_rad': (phase + 2 * math.pi * frequency * duration) % (2 * math.pi)}
        if incoming.get('mass_kg') is not None:
            state['mass_kg'] = incoming['mass_kg']
        if name == 'damped_oscillation' and excitation is not None:
            state['vibration_energy_J'] = excitation * math.exp(-2 * duration / tau)
        if name == 'periodic' and incoming.get('vibration_energy_J') is not None:
            state['vibration_energy_J'] = incoming['vibration_energy_J']
        if incoming.get('energy_J') is not None:
            notes.append('Translational/rebound energy is not converted into modal vibration energy without an excitation model.')
        notes.append('Carrier and envelope are synthesized analytically; amplitude remains uncalibrated. Excitation energy is metadata, not an absolute actuator gain.')
    elif name == 'stochastic':
        rate, duration, seed = get('rate_hz', 2.), get('duration_s', 2.), get('seed', 42)
        count = get('count', None)
        rng = random.Random(seed)
        if count is not None:
            times = sorted(rng.uniform(0, duration) for _ in range(count))
            equations = ['conditional on N=n, event times are sorted Uniform(0,T) samples']
        else:
            times, t = [], rng.expovariate(rate)
            while t < duration:
                times.append(t)
                if len(times) > 8:
                    raise ValueError('Stochastic sample exceeds 8 render events; reduce rate/duration explicitly')
                t += rng.expovariate(rate)
            equations = ['interarrival ~ Exponential(rate)', 'N(T) ~ Poisson(rate*T)']
        for t in times:
            strength = rng.uniform(.4, 1.)
            seg(start + t, .15, strength)
            samples.append(dict(time_s=start + t, relative_strength=strength))
        process_end = start + duration
        notes.append('Independent stochastic contact process; random amplitude range [0.4,1] is a design assumption. Empty realizations are valid.')
    elif name == 'rhythmic_action':
        count = get('count', 4)
        interval = get('interval_s', .35)
        bpm = get('tempo_bpm', None)
        if bpm is not None and raw.get('interval_s') is None:
            interval = 60 / bpm
            values['interval_s'], origin['interval_s'] = interval, 'derived_from_tempo'
        elif bpm is not None and not math.isclose(interval, 60 / bpm, rel_tol=.01):
            raise ValueError('interval_s and tempo_bpm conflict')
        interval_ratio, strength_ratio = get('interval_ratio', 1.), get('strength_ratio', 1.)
        t = start
        for k in range(count):
            seg(t, .15, strength_ratio ** k)
            samples.append(dict(time_s=t, relative_strength=strength_ratio ** k))
            if k < count - 1:
                t += interval * interval_ratio ** k
        process_end = t + .15
        equations = ['dt_k=interval*interval_ratio^k', 'strength_k=strength_ratio^k']
        notes.append('Behavioral cadence model, not a physical law. Unspecified interval/strength ratios default to steady repetition, not automatic decay.')
    else:
        raise ValueError(f'Unimplemented model: {name}')

    if len(segments) > 8:
        raise ValueError('Model emits more than 8 render events')
    if process_end > 10 or any(s['start'] + s['duration'] > 10 for s in segments):
        raise ValueError('Model exceeds the 10-second renderer window; parameters are not automatically compressed')
    for s in segments:
        dc.SubEvent.model_validate({k: v for k, v in s.items() if k not in ('envelope', 'synthesis')})
    if any(b['start'] - a['start'] < a['duration'] for a, b in zip(segments, segments[1:])):
        notes.append('Rendering windows overlap; physical event times are not stretched apart.')
    return dict(sub_events=segments, process_duration_s=process_end, terminal_state=state,
                physics=dict(version=name + '_v1', model_kind=REGISTRY[name].family,
                             setup=raw, parameters=values, provenance=origin, equations=equations,
                             estimates=estimates.model_dump() if estimates else None,
                             omitted=omitted or None,
                             incoming_state=incoming, terminal_state=state, samples=samples,
                             notes=notes + ['Source/parameter extraction is an LM judgment. Defaults are unmeasured assumptions.',
                                            'LM estimates (if any) are plausibility judgments with stated ranges, not measurements.',
                                            'Normalized amplitude is not calibrated perceived strength or cross-model force.']))
