# Physical properties of the described objects/situation that an LM may estimate when unstated.
# Counts, times, seeds and ratios are scenario choices, not properties, and are never estimated.
ESTIMABLE = ('height_m', 'normal_speed_m_s', 'speed_m_s', 'mass_kg', 'restitution', 'friction_coefficient',
             'rolling_resistance', 'frequency_hz', 'damping_ratio', 'rate_hz', 'interval_s')
# Parameter -> incoming-state key that solve() inherits it from (inheritance outranks estimation).
INHERITS = {'height_m': 'height_m', 'mass_kg': 'mass_kg', 'normal_speed_m_s': 'normal_speed_m_s',
            'speed_m_s': 'horizontal_speed_m_s', 'vertical_velocity_m_s': 'vertical_velocity_m_s',
            'excitation_energy_J': 'vibration_energy_J'}


class Estimate(dc.Output):
    value: float | None
    low: float | None
    high: float | None
    basis: str = Field(min_length=1, max_length=300)

    @model_validator(mode='after')
    def coherent_range(self):
        given = [v is not None for v in (self.value, self.low, self.high)]
        if any(given) and not all(given):
            raise ValueError('value, low and high must be all null or all numbers')
        if all(given) and not self.low <= self.value <= self.high:
            raise ValueError('estimate must satisfy low <= value <= high')
        return self


def missing_estimable(name, setup, incoming=None):
    """Estimable parameters of the model that are neither stated nor inherited."""
    raw, incoming = setup.model_dump(), incoming or {}
    return [k for k in REGISTRY[name].parameters if k in ESTIMABLE and raw.get(k) is None
            and incoming.get(INHERITS.get(k, '')) is None]


def estimate_type(name, keys):
    fields = {}
    for key in keys:
        kind, bounds, description = FIELDS[key]
        number = (float | None, Field(**bounds))
        fields[key] = (create_model(f'{name}_{key}_estimate', __base__=Estimate,
                                    value=number, low=number, high=number),
                       Field(description=description))
    return create_model(name + '_estimates', __base__=dc.Output, **fields)


